/**
 * Check the YouTube ingest path.
 *
 * Offline by default — URL resolution, chapter parsing and transcript rendering
 * need no keys or network:
 *
 *   npx tsx scripts/verify-youtube.ts
 *
 * Pass `--live` to additionally hit the YouTube Data API and pull a real
 * transcript. That needs YOUTUBE_API_KEY, so load the env file:
 *
 *   node --env-file=.env node_modules/.bin/tsx scripts/verify-youtube.ts --live
 */
import { PDFDocument } from "pdf-lib";

import { textToPdf } from "../src/rag/ingest/text-to-pdf.ts";
import { parseChapters } from "../src/rag/youtube/chapters.ts";
import {
  fetchPlaylist,
  fetchPlaylistEntries,
  fetchVideo,
  parseIsoDuration,
} from "../src/rag/youtube/data-api.ts";
import { fetchTranscript } from "../src/rag/youtube/transcript.ts";
import { renderTranscriptDocument } from "../src/rag/youtube/transcript-document.ts";
import { resolveYoutubeUrl, YoutubeUrlError } from "../src/rag/youtube/url.ts";

const LIVE = process.argv.includes("--live");

/** A well-known video with human-written captions and description chapters. */
const LIVE_VIDEO = process.env.VERIFY_VIDEO_ID ?? "dQw4w9WgXcQ";
const LIVE_PLAYLIST =
  process.env.VERIFY_PLAYLIST_ID ?? "PLrAXtmErZgOeiKm4sgNOknGvNjby9efdf";

const URLS = [
  "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
  "https://youtu.be/dQw4w9WgXcQ?si=abc",
  "https://www.youtube.com/shorts/dQw4w9WgXcQ",
  "https://www.youtube.com/live/dQw4w9WgXcQ",
  "youtube.com/playlist?list=PLrAXtmErZgOeiKm4sgNOknGvNjby9efdf",
  "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PLrAXtmErZgOeiKm4sgNOknGvNjby9efdf",
  "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=WL",
  "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=RDdQw4w9WgXcQ",
  "https://vimeo.com/12345",
  "dQw4w9WgXcQ",
];

const DESCRIPTION = `A walkthrough of the ingest pipeline.

0:00 Introduction
1:30 - Parsing the transcript
04:15 Building the tree
1:02:40 Wrapping up

Follow us at 9:00 every morning.`;

function describeTarget(url: string): string {
  try {
    const target = resolveYoutubeUrl(url);

    switch (target.kind) {
      case "video":
        return `video ${target.videoId}`;
      case "playlist":
        return `playlist ${target.playlistId}`;
      case "ambiguous":
        return `ambiguous (video ${target.videoId} / playlist ${target.playlistId})`;
    }
  } catch (error) {
    return error instanceof YoutubeUrlError
      ? `rejected: ${error.message}`
      : `error: ${String(error)}`;
  }
}

function syntheticCues() {
  // Rolling auto-generated captions: each cue repeats the tail of the previous.
  return [
    { startSeconds: 0, durationSeconds: 3, text: "welcome to the" },
    { startSeconds: 2, durationSeconds: 3, text: "welcome to the pipeline talk" },
    { startSeconds: 5, durationSeconds: 4, text: "today we cover retrieval." },
    { startSeconds: 95, durationSeconds: 4, text: "Parsing starts with cues." },
    {
      startSeconds: 260,
      durationSeconds: 5,
      text: "The tree is built from headings and it is what the router reads.",
    },
    { startSeconds: 3765, durationSeconds: 4, text: "That is a wrap, thanks." },
  ];
}

async function offlineChecks() {
  console.log("--- resolveYoutubeUrl ---");
  for (const url of URLS) {
    console.log(`${url.padEnd(78)} -> ${describeTarget(url)}`);
  }

  console.log("\n--- resolveYoutubeUrl with preference ---");
  const both =
    "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PLrAXtmErZgOeiKm4sgNOknGvNjby9efdf";
  console.log("video:   ", JSON.stringify(resolveYoutubeUrl(both, "video")));
  console.log("playlist:", JSON.stringify(resolveYoutubeUrl(both, "playlist")));

  console.log("\n--- parseIsoDuration ---");
  for (const iso of ["PT1H2M30S", "PT45S", "PT12M", "P0D", undefined]) {
    console.log(`${String(iso).padEnd(10)} -> ${parseIsoDuration(iso)}s`);
  }

  console.log("\n--- parseChapters ---");
  const chapters = parseChapters(DESCRIPTION);
  console.log(`${chapters.length} chapters`);
  for (const chapter of chapters) {
    console.log(`  ${chapter.startSeconds}s | ${chapter.title}`);
  }
  console.log(
    "two timestamps only ->",
    parseChapters("0:00 Intro\n5:00 Outro").length,
    "chapters (needs 3+)",
  );

  console.log("\n--- renderTranscriptDocument (with chapters) ---");
  const rendered = renderTranscriptDocument(
    {
      videoId: "abc12345678",
      title: "Building a vectorless RAG pipeline",
      description: DESCRIPTION,
      channelTitle: "Polyglot",
      publishedAt: "2026-01-15T10:00:00Z",
      durationSeconds: 3800,
      thumbnailUrl: null,
      defaultLanguage: "en",
      isLive: false,
    },
    { cues: syntheticCues(), languageCode: "en", autoGenerated: true },
  );

  console.log(`sections: ${rendered.sectionCount}, words: ${rendered.wordCount}`);
  console.log(rendered.text);

  console.log("\n--- renderTranscriptDocument (no chapters, time windows) ---");
  const windowed = renderTranscriptDocument(
    {
      videoId: "abc12345678",
      title: "Unchaptered talk",
      description: "No timestamps here.",
      channelTitle: "Polyglot",
      publishedAt: "2026-01-15T10:00:00Z",
      durationSeconds: 3800,
      thumbnailUrl: null,
      defaultLanguage: "en",
      isLive: false,
    },
    { cues: syntheticCues(), languageCode: "en", autoGenerated: true },
  );

  console.log(
    `sections: ${windowed.sectionCount}`,
    "\nheadings:",
    windowed.text.match(/^## .*/gm),
  );

  console.log("\n--- textToPdf on the rendered transcript ---");
  const pdf = await textToPdf(rendered.text, { title: "Transcript check" });
  const reloaded = await PDFDocument.load(pdf);
  console.log(`pdf bytes: ${pdf.length}, pages: ${reloaded.getPageCount()}`);
}

/**
 * Transcript fetching needs no API key — it reads YouTube's InnerTube player
 * endpoint — so it stays checkable when only the Data API half is unconfigured.
 */
function stubMetadata(videoId: string) {
  return {
    videoId,
    title: `Video ${videoId}`,
    description: "",
    channelTitle: "unknown",
    publishedAt: new Date().toISOString(),
    durationSeconds: 0,
    thumbnailUrl: null,
    defaultLanguage: null,
    isLive: false,
  };
}

async function liveChecks() {
  const hasApiKey = Boolean(process.env.YOUTUBE_API_KEY);

  console.log("\n--- fetchVideo (live) ---");

  if (!hasApiKey) {
    console.log(
      "YOUTUBE_API_KEY is not set; skipping Data API checks and using stub metadata.",
    );
  }

  const video = hasApiKey
    ? await fetchVideo(LIVE_VIDEO)
    : stubMetadata(LIVE_VIDEO);

  if (!video) {
    console.log(`${LIVE_VIDEO} is unavailable`);
    return;
  }

  if (hasApiKey) {
    console.log(
      `${video.videoId} | ${video.title} | ${video.channelTitle} | ${video.durationSeconds}s | live: ${video.isLive}`,
    );
  }

  console.log("\n--- fetchTranscript (live) ---");
  const transcript = await fetchTranscript(video.videoId);
  console.log(
    `${transcript.cues.length} cues | ${transcript.languageCode} | auto: ${transcript.autoGenerated}`,
  );
  console.log(
    transcript.cues
      .slice(0, 3)
      .map((cue) => `  ${cue.startSeconds}s: ${cue.text}`)
      .join("\n"),
  );

  const document = renderTranscriptDocument(video, transcript);
  console.log(
    `\nrendered: ${document.sectionCount} sections, ${document.wordCount} words`,
  );
  console.log("headings:", document.text.match(/^## .*/gm)?.slice(0, 8));
  console.log("\nfirst 600 chars:\n", document.text.slice(0, 600));

  if (!hasApiKey) return;

  console.log("\n--- fetchPlaylist + fetchPlaylistEntries (live) ---");
  const playlist = await fetchPlaylist(LIVE_PLAYLIST);
  console.log(
    playlist
      ? `${playlist.title} | ${playlist.channelTitle} | ${playlist.itemCount} items`
      : `${LIVE_PLAYLIST} is unavailable`,
  );

  if (playlist) {
    const listing = await fetchPlaylistEntries(LIVE_PLAYLIST);
    console.log(
      `entries: ${listing.entries.length}, truncated: ${listing.truncated}, unavailable: ${listing.unavailableCount}`,
    );
    console.log(
      listing.entries
        .slice(0, 5)
        .map((entry) => `  #${entry.position} ${entry.videoId} ${entry.title}`)
        .join("\n"),
    );
  }
}

async function main() {
  await offlineChecks();

  if (LIVE) {
    await liveChecks();
  } else {
    console.log("\n(skipping live API checks; pass --live to run them)");
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
