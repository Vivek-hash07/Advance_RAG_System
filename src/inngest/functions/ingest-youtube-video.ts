import { NonRetriableError } from "inngest";

import { inngest } from "@/src/inngest/client";
import { videoRequested } from "@/src/inngest/events";
import { MAX_POLL_ATTEMPTS, pollDelay, POLL_BUDGET_MINUTES } from "@/src/inngest/polling";
import * as repository from "@/src/rag/documents/repository";
import type { IngestStatus } from "@/src/rag/types";
import {
  failVideo,
  isVideoIndexed,
  pollVideoTree,
  submitVideoTranscript,
  syncVideoMetadata,
  VideoIngestError,
} from "@/src/rag/youtube/video-ingest";

/**
 * Mirror the shared video's state onto the user-facing source row, when one is
 * waiting on it. Playlist fan-out has no document of its own — the playlist row
 * tracks its own progress — so this is a no-op there.
 */
async function reflectOnDocument(
  documentId: string | null | undefined,
  status: IngestStatus,
  errorMessage: string | null,
): Promise<void> {
  if (!documentId) return;

  await repository
    .updateDocumentStatus(documentId, { status, errorMessage })
    .catch(() => undefined);
}

/**
 * Transcribe and index one YouTube video.
 *
 * Runs at video-id granularity, not per user or per playlist, because the same
 * video often appears in several playlists and there is no reason to fetch,
 * render and index it more than once. The whole pipeline stays vectorless: the
 * captions become a structured document, PageIndex turns that into a tree, and
 * retrieval later reasons over the tree.
 */
export const ingestYoutubeVideo = inngest.createFunction(
  {
    id: "ingest-youtube-video",
    name: "Index YouTube video",
    triggers: { event: videoRequested },
    // One run per video, so a playlist fan-out and an on-demand request for the
    // same video cannot both transcribe it.
    concurrency: [
      { key: "event.data.videoId", limit: 1 },
      { limit: 5 },
    ],
    retries: 2,
  },
  async ({ event, step, logger }) => {
    const { videoId, documentId, playlistId, trigger } = event.data;

    logger.info("Indexing YouTube video", { videoId, playlistId, trigger });

    const alreadyIndexed = await step.run("check-cache", () =>
      isVideoIndexed(videoId),
    );

    if (alreadyIndexed) {
      logger.info("Video already indexed, reusing cached tree", { videoId });
      await step.run("link-cached-video", () =>
        reflectOnDocument(documentId, "ready", null),
      );
      return { videoId, status: "ready", cached: true };
    }

    const metadata = await step.run("fetch-metadata", () =>
      syncVideoMetadata(videoId),
    );

    if (!metadata.available) {
      const reason = metadata.reason ?? "This video cannot be read.";
      logger.warn("Video unavailable", { videoId, reason });

      await step.run("mark-unavailable", async () => {
        await failVideo(videoId, reason);
        await reflectOnDocument(documentId, "failed", reason);
      });

      return { videoId, status: "failed", reason };
    }

    const submission = await step.run("submit-transcript", async () => {
      try {
        return await submitVideoTranscript(videoId);
      } catch (error) {
        if (error instanceof VideoIngestError) {
          // No captions, private video, empty track: retrying cannot help.
          await failVideo(videoId, error.message);
          await reflectOnDocument(documentId, "failed", error.message);
          throw new NonRetriableError(error.message);
        }
        throw error;
      }
    });

    logger.info("Transcript submitted to PageIndex", {
      videoId,
      pageIndexDocId: submission.pageIndexDocId,
      language: submission.languageCode,
      autoGenerated: submission.autoGenerated,
      sections: submission.sectionCount,
      words: submission.wordCount,
    });

    for (let attempt = 0; attempt < MAX_POLL_ATTEMPTS; attempt += 1) {
      const result = await step.run(`poll-tree-${attempt}`, () =>
        pollVideoTree(videoId),
      );

      if (result.status === "ready") {
        logger.info("Video indexed", { videoId, nodes: result.nodeCount });
        await step.run("mark-document-ready", () =>
          reflectOnDocument(documentId, "ready", null),
        );
        return { videoId, status: "ready", nodes: result.nodeCount };
      }

      if (result.status === "failed") {
        const reason = "PageIndex could not process this transcript.";
        logger.error("Video indexing failed", { videoId, reason });
        await step.run("mark-document-failed", () =>
          reflectOnDocument(documentId, "failed", reason),
        );
        return { videoId, status: "failed", reason };
      }

      await step.sleep(`wait-${attempt}`, pollDelay(attempt));
    }

    const reason = `PageIndex did not finish this transcript within ${POLL_BUDGET_MINUTES} minutes.`;

    await step.run("mark-timed-out", async () => {
      await failVideo(videoId, reason);
      await reflectOnDocument(documentId, "failed", reason);
    });

    return { videoId, status: "failed", reason };
  },
);
