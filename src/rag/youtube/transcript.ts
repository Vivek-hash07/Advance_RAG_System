const PLAYER_ENDPOINT = "https://www.youtube.com/youtubei/v1/player";

/**
 * InnerTube clients that still return caption tracks for anonymous callers.
 *
 * The `WEB` client now requires a proof-of-origin token and answers
 * `UNPLAYABLE` without one, so the mobile clients are tried instead — the same
 * endpoint the public transcript libraries use, with no HTML scraping.
 */
const CLIENTS = [
  {
    name: "ANDROID",
    context: {
      clientName: "ANDROID",
      clientVersion: "20.10.38",
      androidSdkVersion: 30,
      hl: "en",
      gl: "US",
    },
    userAgent:
      "com.google.android.youtube/20.10.38 (Linux; U; Android 11) gzip",
  },
  {
    name: "IOS",
    context: {
      clientName: "IOS",
      clientVersion: "20.10.4",
      deviceModel: "iPhone16,2",
      hl: "en",
      gl: "US",
    },
    userAgent:
      "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3 like Mac OS X)",
  },
] as const;

export class TranscriptUnavailableError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TranscriptUnavailableError";
  }
}

export interface TranscriptCue {
  startSeconds: number;
  durationSeconds: number;
  text: string;
}

export interface FetchedTranscript {
  cues: TranscriptCue[];
  languageCode: string;
  /** True when the captions were machine generated rather than authored. */
  autoGenerated: boolean;
}

interface CaptionTrack {
  baseUrl: string;
  languageCode: string;
  kind?: string;
  name?: { simpleText?: string; runs?: Array<{ text?: string }> };
}

interface PlayerResponse {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: { title?: string; isLiveContent?: boolean };
  captions?: {
    playerCaptionsTracklistRenderer?: { captionTracks?: CaptionTrack[] };
  };
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/** How long caption downloads stay quiet after YouTube returns 429. */
export const CAPTION_PAUSE_MS = 10 * 60 * 1000;

export const CAPTION_RATE_LIMIT_MESSAGE =
  "YouTube is rate-limiting caption downloads from this network. They will be tried again in about 10 minutes.";

let captionsPausedUntil = 0;

/** True while another caption request would only extend the rate limit. */
export function captionsPaused(): boolean {
  return Date.now() < captionsPausedUntil;
}

/** Milliseconds until a caption download is worth trying again. */
export function captionPauseRemainingMs(): number {
  return Math.max(0, captionsPausedUntil - Date.now());
}

function noteCaptionRateLimit(): void {
  captionsPausedUntil = Date.now() + CAPTION_PAUSE_MS;
}

/** One caption download at a time, with a gap, so a playlist does not trip 429. */
let captionSlot: Promise<void> = Promise.resolve();

function takeCaptionSlot(): Promise<() => void> {
  let release: () => void = () => undefined;
  const previous = captionSlot;
  captionSlot = new Promise<void>((resolve) => {
    release = resolve;
  });

  return previous.then(async () => {
    await sleep(4_000);
    return release;
  });
}

async function requestPlayer(
  videoId: string,
  client: (typeof CLIENTS)[number],
): Promise<PlayerResponse> {
  const response = await fetch(PLAYER_ENDPOINT, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "User-Agent": client.userAgent,
      "Accept-Language": "en-US,en",
    },
    body: JSON.stringify({
      videoId,
      context: { client: client.context },
      contentCheckOk: true,
      racyCheckOk: true,
    }),
    cache: "no-store",
  });

  if (response.status === 429 || response.status === 503) {
    noteCaptionRateLimit();
    throw new TranscriptUnavailableError(CAPTION_RATE_LIMIT_MESSAGE);
  }

  if (!response.ok) {
    throw new TranscriptUnavailableError(
      `YouTube returned ${response.status} when loading the video player.`,
    );
  }

  return (await response.json()) as PlayerResponse;
}

function describeUnplayable(status: string, reason: string | undefined): string {
  switch (status) {
    case "LOGIN_REQUIRED":
      return "This video is private or age restricted, so its transcript cannot be read.";
    case "UNPLAYABLE":
      return reason ?? "This video cannot be played, so it has no readable transcript.";
    case "ERROR":
      return "This video no longer exists.";
    case "LIVE_STREAM_OFFLINE":
      return "This live stream has not started yet.";
    default:
      return reason ?? `YouTube reported the video as ${status}.`;
  }
}

/**
 * Rank the available caption tracks.
 *
 * Human-authored captions beat auto-generated ones because ASR output has no
 * punctuation or speaker turns, and a preferred language beats both.
 */
function pickTrack(tracks: CaptionTrack[]): CaptionTrack {
  const preferred = ragConfig.youtube.transcriptLanguages;

  const score = (track: CaptionTrack): number => {
    const base = track.languageCode.split("-")[0].toLowerCase();
    const languageRank = preferred.findIndex(
      (code) => code.toLowerCase().split("-")[0] === base,
    );

    // Lower is better: language priority dominates, authored beats ASR.
    const languageScore = languageRank === -1 ? preferred.length : languageRank;
    const kindScore = track.kind === "asr" ? 1 : 0;

    return languageScore * 2 + kindScore;
  };

  return [...tracks].sort((a, b) => score(a) - score(b))[0];
}

function decodeEntities(input: string): string {
  return input
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, code: string) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code: string) =>
      String.fromCodePoint(Number.parseInt(code, 16)),
    );
}

function cleanCueText(input: string): string {
  return decodeEntities(input)
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

interface Json3Response {
  events?: Array<{
    tStartMs?: number;
    dDurationMs?: number;
    segs?: Array<{ utf8?: string }>;
  }>;
}

function parseJson3(body: string): TranscriptCue[] {
  const parsed = JSON.parse(body) as Json3Response;
  const cues: TranscriptCue[] = [];

  for (const event of parsed.events ?? []) {
    if (typeof event.tStartMs !== "number") continue;

    const text = cleanCueText(
      (event.segs ?? []).map((segment) => segment.utf8 ?? "").join(""),
    );
    if (!text) continue;

    cues.push({
      startSeconds: event.tStartMs / 1000,
      durationSeconds: (event.dDurationMs ?? 0) / 1000,
      text,
    });
  }

  return cues;
}

/** Fallback for the legacy `srv3`/`ttml` XML the older caption URLs return. */
function parseTimedTextXml(body: string): TranscriptCue[] {
  const cues: TranscriptCue[] = [];
  const pattern = /<(?:p|text)\b([^>]*)>([\s\S]*?)<\/(?:p|text)>/g;

  let match: RegExpExecArray | null;
  while ((match = pattern.exec(body)) !== null) {
    const attributes = match[1];
    const start =
      attributes.match(/\bt="(\d+)"/)?.[1] ?? attributes.match(/\bstart="([\d.]+)"/)?.[1];
    if (start === undefined) continue;

    const text = cleanCueText(match[2]);
    if (!text) continue;

    const duration =
      attributes.match(/\bd="(\d+)"/)?.[1] ?? attributes.match(/\bdur="([\d.]+)"/)?.[1];

    // `t`/`d` are milliseconds, `start`/`dur` are seconds.
    const isMilliseconds = /\bt="/.test(attributes);

    cues.push({
      startSeconds: Number(start) / (isMilliseconds ? 1000 : 1),
      durationSeconds: Number(duration ?? 0) / (isMilliseconds ? 1000 : 1),
      text,
    });
  }

  return cues;
}

async function downloadTrack(
  track: CaptionTrack,
  videoId: string,
  userAgent: string,
): Promise<TranscriptCue[]> {
  if (captionsPaused()) {
    throw new TranscriptUnavailableError(CAPTION_RATE_LIMIT_MESSAGE);
  }

  const url = new URL(track.baseUrl);
  url.searchParams.set("fmt", "json3");
  const release = await takeCaptionSlot();

  let response: Response;
  try {
    response = await fetch(url, {
      headers: {
        "User-Agent": userAgent,
        Accept: "*/*",
        "Accept-Language": "en-US,en",
        Referer: `https://www.youtube.com/watch?v=${videoId}`,
      },
      cache: "no-store",
    });
  } finally {
    release();
  }

  if (response.status === 429 || response.status === 503) {
    noteCaptionRateLimit();
    throw new TranscriptUnavailableError(CAPTION_RATE_LIMIT_MESSAGE);
  }

  if (!response.ok) {
    throw new TranscriptUnavailableError(
      `YouTube returned ${response.status} when downloading the captions.`,
    );
  }

  const body = await response.text();
  if (!body.trim()) {
    return [];
  }

  return body.trimStart().startsWith("<")
    ? parseTimedTextXml(body)
    : parseJson3(body);
}

/**
 * Read a video's captions straight from YouTube's InnerTube player API.
 *
 * The Data API cannot serve caption bodies without the channel owner's OAuth
 * token, so this is the only route to a transcript for arbitrary public videos.
 */
export async function fetchTranscript(
  videoId: string,
): Promise<FetchedTranscript> {
  if (captionsPaused()) {
    throw new TranscriptUnavailableError(CAPTION_RATE_LIMIT_MESSAGE);
  }

  let lastStatus: { status: string; reason?: string } | null = null;
  let tracks: CaptionTrack[] | undefined;
  let userAgent: string = CLIENTS[0].userAgent;

  for (const client of CLIENTS) {
    const player = await requestPlayer(videoId, client);
    const status = player.playabilityStatus?.status ?? "UNKNOWN";

    if (status !== "OK") {
      lastStatus = { status, reason: player.playabilityStatus?.reason };
      continue;
    }

    tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks;
    if (tracks?.length) {
      userAgent = client.userAgent;
      break;
    }

    // Playable but captionless: no other client will do better.
    lastStatus = null;
    break;
  }

  if (lastStatus) {
    throw new TranscriptUnavailableError(
      describeUnplayable(lastStatus.status, lastStatus.reason),
    );
  }

  if (!tracks?.length) {
    throw new TranscriptUnavailableError(
      "This video has no captions, so there is no transcript to index.",
    );
  }

  const track = pickTrack(tracks);
  const cues = await downloadTrack(track, videoId, userAgent);

  if (cues.length === 0) {
    throw new TranscriptUnavailableError(
      "This video's caption track is empty.",
    );
  }

  return {
    cues: cues.sort((a, b) => a.startSeconds - b.startSeconds),
    languageCode: track.languageCode,
    autoGenerated: track.kind === "asr",
  };
}
