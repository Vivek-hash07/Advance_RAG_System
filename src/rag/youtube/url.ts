/**
 * A pasted YouTube URL resolved to what the user most likely meant.
 *
 * `ambiguous` is returned for `watch?v=X&list=Y`, which carries both a video and
 * a playlist. We refuse to guess: ingesting 200 videos because someone shared
 * one link is an expensive surprise, so the caller asks instead.
 */
export type YoutubeTarget =
  | { kind: "video"; videoId: string }
  | { kind: "playlist"; playlistId: string }
  | { kind: "ambiguous"; videoId: string; playlistId: string };

export class YoutubeUrlError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "YoutubeUrlError";
  }
}

const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;
const PLAYLIST_ID = /^[A-Za-z0-9_-]{13,42}$/;

const YOUTUBE_HOSTS = new Set([
  "youtube.com",
  "www.youtube.com",
  "m.youtube.com",
  "music.youtube.com",
  "youtube-nocookie.com",
  "www.youtube-nocookie.com",
]);

const SHORT_HOSTS = new Set(["youtu.be", "www.youtu.be"]);

/** Paths that carry the video id as the segment right after the prefix. */
const PATH_VIDEO_PREFIXES = ["/shorts/", "/live/", "/embed/", "/v/"];

/**
 * Playlist ids we cannot ingest.
 *
 * `WL`/`LL` are the viewer's private Watch Later and Liked lists, and `RD`/`UL`
 * prefixes are autogenerated "mix" radios that are personalised per viewer and
 * have no stable contents.
 */
function isIngestablePlaylistId(playlistId: string): boolean {
  if (playlistId === "WL" || playlistId === "LL") return false;
  if (/^(RD|UL|MM)/.test(playlistId)) return false;
  return PLAYLIST_ID.test(playlistId);
}

function normalizeInput(input: string): URL {
  const trimmed = input.trim();

  if (!trimmed) {
    throw new YoutubeUrlError("Paste a YouTube video or playlist link.");
  }

  // Bare ids are a common paste; treat an 11-char token as a video id.
  if (VIDEO_ID.test(trimmed)) {
    return new URL(`https://www.youtube.com/watch?v=${trimmed}`);
  }

  const withProtocol = /^https?:\/\//i.test(trimmed)
    ? trimmed
    : `https://${trimmed}`;

  try {
    return new URL(withProtocol);
  } catch {
    throw new YoutubeUrlError("That does not look like a valid URL.");
  }
}

function extractVideoId(url: URL): string | null {
  if (SHORT_HOSTS.has(url.hostname)) {
    const candidate = url.pathname.slice(1).split("/")[0];
    return VIDEO_ID.test(candidate) ? candidate : null;
  }

  const fromQuery = url.searchParams.get("v");
  if (fromQuery && VIDEO_ID.test(fromQuery)) {
    return fromQuery;
  }

  for (const prefix of PATH_VIDEO_PREFIXES) {
    if (url.pathname.startsWith(prefix)) {
      const candidate = url.pathname.slice(prefix.length).split("/")[0];
      return VIDEO_ID.test(candidate) ? candidate : null;
    }
  }

  return null;
}

export function isYoutubeUrl(input: string): boolean {
  try {
    const url = normalizeInput(input);
    return YOUTUBE_HOSTS.has(url.hostname) || SHORT_HOSTS.has(url.hostname);
  } catch {
    return false;
  }
}

/**
 * Work out whether a link points at one video, a whole playlist, or both.
 *
 * `preference` resolves the both-present case without a round trip, for when the
 * user has already been asked.
 */
export function resolveYoutubeUrl(
  input: string,
  preference?: "video" | "playlist",
): YoutubeTarget {
  const url = normalizeInput(input);

  if (!YOUTUBE_HOSTS.has(url.hostname) && !SHORT_HOSTS.has(url.hostname)) {
    throw new YoutubeUrlError("Only youtube.com and youtu.be links are supported.");
  }

  const videoId = extractVideoId(url);

  const rawPlaylistId = url.searchParams.get("list");
  const playlistId =
    rawPlaylistId && isIngestablePlaylistId(rawPlaylistId) ? rawPlaylistId : null;

  if (videoId && playlistId) {
    if (preference === "video") return { kind: "video", videoId };
    if (preference === "playlist") return { kind: "playlist", playlistId };
    return { kind: "ambiguous", videoId, playlistId };
  }

  if (videoId) {
    return { kind: "video", videoId };
  }

  if (playlistId) {
    return { kind: "playlist", playlistId };
  }

  if (rawPlaylistId) {
    throw new YoutubeUrlError(
      "That playlist cannot be ingested. Watch Later, Liked videos and autogenerated mixes are private or unstable.",
    );
  }

  throw new YoutubeUrlError(
    "No video or playlist found in that link. Use a youtube.com/watch, /shorts, /live or /playlist URL.",
  );
}

export function videoUrl(videoId: string, startSeconds?: number | null): string {
  const base = `https://www.youtube.com/watch?v=${videoId}`;
  return startSeconds && startSeconds > 0 ? `${base}&t=${startSeconds}s` : base;
}

export function playlistUrl(playlistId: string): string {
  return `https://www.youtube.com/playlist?list=${playlistId}`;
}
