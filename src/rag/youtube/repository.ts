import type { Prisma } from "@/src/generated/prisma/client";
import { prisma } from "@/src/lib/db";
import type { YoutubeVideoMetadata } from "@/src/rag/youtube/data-api";
import type { FlatTreeNode, IngestStatus } from "@/src/rag/types";

export type VideoAvailability = "available" | "unavailable" | "live";

/** Transcript build state, which is tracked apart from metadata availability. */
export type TranscriptStatus = "pending" | IngestStatus;

export interface VideoRecord {
  id: string;
  videoId: string;
  title: string;
  description: string;
  channelTitle: string;
  publishedAt: string;
  durationSeconds: number;
  thumbnailUrl: string | null;
  availability: VideoAvailability;
  transcriptStatus: TranscriptStatus;
  errorMessage: string | null;
  pageIndexDocId: string | null;
  summary: string | null;
  hasTree: boolean;
}

const VIDEO_SELECT = {
  id: true,
  videoId: true,
  title: true,
  description: true,
  channelTitle: true,
  publishedAt: true,
  durationSeconds: true,
  thumbnailUrl: true,
  availability: true,
  transcriptStatus: true,
  errorMessage: true,
  pageIndexDocId: true,
  summary: true,
  tree: true,
} as const;

type VideoRow = {
  id: string;
  videoId: string;
  title: string;
  description: string;
  channelTitle: string;
  publishedAt: Date;
  durationSeconds: number;
  thumbnailUrl: string | null;
  availability: string;
  transcriptStatus: string;
  errorMessage: string | null;
  pageIndexDocId: string | null;
  summary: string | null;
  tree: Prisma.JsonValue | null;
};

function toVideoRecord(row: VideoRow): VideoRecord {
  return {
    id: row.id,
    videoId: row.videoId,
    title: row.title,
    description: row.description,
    channelTitle: row.channelTitle,
    publishedAt: row.publishedAt.toISOString(),
    durationSeconds: row.durationSeconds,
    thumbnailUrl: row.thumbnailUrl,
    availability: row.availability as VideoAvailability,
    transcriptStatus: row.transcriptStatus as TranscriptStatus,
    errorMessage: row.errorMessage,
    pageIndexDocId: row.pageIndexDocId,
    summary: row.summary,
    hasTree: row.tree !== null,
  };
}

/**
 * Insert or refresh a video's metadata, leaving any existing transcript work
 * untouched — metadata is cheap to re-fetch, transcripts are not.
 */
export async function upsertVideo(
  metadata: YoutubeVideoMetadata,
): Promise<VideoRecord> {
  const shared = {
    title: metadata.title,
    description: metadata.description,
    channelTitle: metadata.channelTitle,
    publishedAt: new Date(metadata.publishedAt),
    durationSeconds: metadata.durationSeconds,
    thumbnailUrl: metadata.thumbnailUrl,
    availability: (metadata.isLive ? "live" : "available") satisfies VideoAvailability,
  };

  const row = await prisma.youtubeVideo.upsert({
    where: { videoId: metadata.videoId },
    create: { videoId: metadata.videoId, ...shared },
    update: shared,
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

export async function markVideoUnavailable(
  videoId: string,
  title: string,
): Promise<VideoRecord> {
  const shared = {
    availability: "unavailable" satisfies VideoAvailability,
    transcriptStatus: "failed",
    errorMessage: "This video is private, deleted or region blocked.",
  };

  const row = await prisma.youtubeVideo.upsert({
    where: { videoId },
    create: {
      videoId,
      title,
      description: "",
      channelTitle: "",
      publishedAt: new Date(),
      ...shared,
    },
    update: shared,
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

export async function findVideo(videoId: string): Promise<VideoRecord | null> {
  const row = await prisma.youtubeVideo.findUnique({
    where: { videoId },
    select: VIDEO_SELECT,
  });

  return row ? toVideoRecord(row) : null;
}

export async function findVideoByRowId(
  videoRowId: string,
): Promise<VideoRecord | null> {
  const row = await prisma.youtubeVideo.findUnique({
    where: { id: videoRowId },
    select: VIDEO_SELECT,
  });

  return row ? toVideoRecord(row) : null;
}

export async function updateVideoTranscript(
  videoId: string,
  data: {
    transcriptStatus: TranscriptStatus;
    errorMessage?: string | null;
    pageIndexDocId?: string | null;
    transcriptLang?: string | null;
    autoGenerated?: boolean;
    pageCount?: number | null;
    summary?: string | null;
    nodes?: FlatTreeNode[];
  },
): Promise<VideoRecord> {
  const row = await prisma.youtubeVideo.update({
    where: { videoId },
    data: {
      transcriptStatus: data.transcriptStatus,
      ...(data.errorMessage === undefined
        ? {}
        : { errorMessage: data.errorMessage }),
      ...(data.pageIndexDocId === undefined
        ? {}
        : { pageIndexDocId: data.pageIndexDocId }),
      ...(data.transcriptLang === undefined
        ? {}
        : { transcriptLang: data.transcriptLang }),
      ...(data.autoGenerated === undefined
        ? {}
        : { autoGenerated: data.autoGenerated }),
      ...(data.pageCount === undefined ? {} : { pageCount: data.pageCount }),
      ...(data.summary === undefined ? {} : { summary: data.summary }),
      ...(data.nodes === undefined
        ? {}
        : { tree: data.nodes as unknown as Prisma.InputJsonValue }),
    },
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

/** A ready video's cached tree, for the second stage of playlist retrieval. */
export async function findVideoTrees(
  videoIds: string[],
): Promise<Map<string, FlatTreeNode[]>> {
  if (videoIds.length === 0) return new Map();

  const rows = await prisma.youtubeVideo.findMany({
    where: { videoId: { in: videoIds }, transcriptStatus: "ready" },
    select: { videoId: true, tree: true },
  });

  const trees = new Map<string, FlatTreeNode[]>();

  for (const row of rows) {
    if (Array.isArray(row.tree) && row.tree.length > 0) {
      trees.set(row.videoId, row.tree as unknown as FlatTreeNode[]);
    }
  }

  return trees;
}

export interface PlaylistRecord {
  id: string;
  playlistId: string;
  title: string;
  description: string;
  channelTitle: string;
  itemCount: number;
  truncated: boolean;
  unavailableCount: number;
  lastSyncedAt: string;
}

const PLAYLIST_SELECT = {
  id: true,
  playlistId: true,
  title: true,
  description: true,
  channelTitle: true,
  itemCount: true,
  truncated: true,
  unavailableCount: true,
  lastSyncedAt: true,
} as const;

type PlaylistRow = Omit<PlaylistRecord, "lastSyncedAt"> & { lastSyncedAt: Date };

function toPlaylistRecord(row: PlaylistRow): PlaylistRecord {
  return { ...row, lastSyncedAt: row.lastSyncedAt.toISOString() };
}

export async function upsertPlaylist(input: {
  playlistId: string;
  title: string;
  description: string;
  channelTitle: string;
  itemCount: number;
  truncated: boolean;
  unavailableCount: number;
}): Promise<PlaylistRecord> {
  const shared = { ...input, lastSyncedAt: new Date() };

  const row = await prisma.youtubePlaylist.upsert({
    where: { playlistId: input.playlistId },
    create: shared,
    update: shared,
    select: PLAYLIST_SELECT,
  });

  return toPlaylistRecord(row);
}

export async function findPlaylist(
  playlistId: string,
): Promise<PlaylistRecord | null> {
  const row = await prisma.youtubePlaylist.findUnique({
    where: { playlistId },
    select: PLAYLIST_SELECT,
  });

  return row ? toPlaylistRecord(row) : null;
}

/**
 * Replace a playlist's membership in one transaction.
 *
 * Playlists are mutable, so a refresh has to drop videos that were removed as
 * well as add new ones; the videos themselves survive because they are cached
 * independently and may belong to other playlists.
 */
export async function replacePlaylistItems(
  playlistRowId: string,
  items: Array<{ videoRowId: string; position: number }>,
): Promise<void> {
  await prisma.$transaction([
    prisma.youtubePlaylistItem.deleteMany({
      where: {
        playlistId: playlistRowId,
        videoId: { notIn: items.map((item) => item.videoRowId) },
      },
    }),
    ...items.map((item) =>
      prisma.youtubePlaylistItem.upsert({
        where: {
          playlistId_videoId: {
            playlistId: playlistRowId,
            videoId: item.videoRowId,
          },
        },
        create: {
          playlistId: playlistRowId,
          videoId: item.videoRowId,
          position: item.position,
        },
        update: { position: item.position },
      }),
    ),
  ]);
}

/**
 * The playlist-level index: one row per video with just enough to decide which
 * video a question is about. Deliberately excludes trees and transcripts —
 * routing must stay cheap.
 */
export interface PlaylistIndexEntry {
  videoId: string;
  position: number;
  title: string;
  channelTitle: string;
  publishedAt: string;
  durationSeconds: number;
  summary: string | null;
  /** First lines of the description, as a fallback when no summary exists yet. */
  descriptionGist: string;
  availability: VideoAvailability;
  transcriptStatus: TranscriptStatus;
}

export async function loadPlaylistIndex(
  playlistId: string,
): Promise<PlaylistIndexEntry[]> {
  const rows = await prisma.youtubePlaylistItem.findMany({
    where: { playlist: { playlistId } },
    orderBy: { position: "asc" },
    select: {
      position: true,
      video: {
        select: {
          videoId: true,
          title: true,
          description: true,
          channelTitle: true,
          publishedAt: true,
          durationSeconds: true,
          summary: true,
          availability: true,
          transcriptStatus: true,
        },
      },
    },
  });

  return rows.map((row) => ({
    videoId: row.video.videoId,
    position: row.position,
    title: row.video.title,
    channelTitle: row.video.channelTitle,
    publishedAt: row.video.publishedAt.toISOString(),
    durationSeconds: row.video.durationSeconds,
    summary: row.video.summary,
    descriptionGist: row.video.description.replace(/\s+/g, " ").slice(0, 300),
    availability: row.video.availability as VideoAvailability,
    transcriptStatus: row.video.transcriptStatus as TranscriptStatus,
  }));
}

/** Videos in a playlist whose transcript has not been built yet. */
export async function findUnbuiltPlaylistVideos(
  playlistId: string,
): Promise<string[]> {
  const rows = await prisma.youtubePlaylistItem.findMany({
    where: {
      playlist: { playlistId },
      video: { transcriptStatus: "pending", availability: "available" },
    },
    orderBy: { position: "asc" },
    select: { video: { select: { videoId: true } } },
  });

  return rows.map((row) => row.video.videoId);
}

/** How far along a playlist's video transcripts are, for status reporting. */
export interface PlaylistProgress {
  totalVideos: number;
  readyVideos: number;
  pendingVideos: number;
  failedVideos: number;
}

export async function summarizePlaylistProgress(
  playlistRowId: string,
): Promise<PlaylistProgress> {
  const grouped = await prisma.youtubePlaylistItem.findMany({
    where: { playlistId: playlistRowId },
    select: { video: { select: { transcriptStatus: true } } },
  });

  const progress: PlaylistProgress = {
    totalVideos: grouped.length,
    readyVideos: 0,
    pendingVideos: 0,
    failedVideos: 0,
  };

  for (const row of grouped) {
    switch (row.video.transcriptStatus) {
      case "ready":
        progress.readyVideos += 1;
        break;
      case "failed":
        progress.failedVideos += 1;
        break;
      default:
        progress.pendingVideos += 1;
    }
  }

  return progress;
}

/** PageIndex documents that would be orphaned by deleting this playlist. */
export async function findOrphanedPlaylistDocIds(
  playlistRowId: string,
): Promise<string[]> {
  const rows = await prisma.youtubeVideo.findMany({
    where: {
      pageIndexDocId: { not: null },
      playlistItems: { some: { playlistId: playlistRowId } },
      // Keep anything another playlist or a standalone source still points at.
      AND: [
        { playlistItems: { none: { playlistId: { not: playlistRowId } } } },
        { documents: { none: {} } },
      ],
    },
    select: { pageIndexDocId: true },
  });

  return rows
    .map((row) => row.pageIndexDocId)
    .filter((docId): docId is string => docId !== null);
}

export async function countPlaylistsForVideo(
  videoRowId: string,
): Promise<number> {
  return prisma.youtubePlaylistItem.count({ where: { videoId: videoRowId } });
}

/** Drop a cached video, returning the PageIndex document that can now go too. */
export async function deleteVideoByRowId(
  videoRowId: string,
): Promise<string | null> {
  const row = await prisma.youtubeVideo
    .delete({ where: { id: videoRowId }, select: { pageIndexDocId: true } })
    .catch(() => null);

  return row?.pageIndexDocId ?? null;
}

/**
 * Drop a cached playlist along with the videos only it referenced, leaving
 * videos that other playlists or standalone sources still use.
 */
export async function deletePlaylistByRowId(
  playlistRowId: string,
): Promise<void> {
  await prisma.youtubeVideo.deleteMany({
    where: {
      playlistItems: { some: { playlistId: playlistRowId } },
      AND: [
        { playlistItems: { none: { playlistId: { not: playlistRowId } } } },
        { documents: { none: {} } },
      ],
    },
  });

  await prisma.youtubePlaylist
    .delete({ where: { id: playlistRowId } })
    .catch(() => undefined);
}
