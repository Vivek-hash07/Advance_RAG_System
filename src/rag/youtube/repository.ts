import { Prisma } from "@/src/generated/prisma/client";
import { prisma } from "@/src/lib/db";
import type { YoutubeVideoMetadata } from "@/src/rag/youtube/data-api";
import type { FlatTreeNode, IngestStatus } from "@/src/rag/types";

export type VideoAvailability = "available" | "unavailable" | "live";

/** Transcript build state, which is tracked apart from metadata availability. */
export type TranscriptStatus = "pending" | IngestStatus;

export interface VideoRecord {
  id: string;
  videoId: string;
  title: string;
  description: string;
  channelTitle: string;
  publishedAt: string;
  durationSeconds: number;
  thumbnailUrl: string | null;
  availability: VideoAvailability;
  transcriptStatus: TranscriptStatus;
  errorMessage: string | null;
  pageIndexDocId: string | null;
  summary: string | null;
  chunkCount: number;
  hasTree: boolean;
}

const VIDEO_SELECT = {
  id: true,
  videoId: true,
  title: true,
  description: true,
  channelTitle: true,
  publishedAt: true,
  durationSeconds: true,
  thumbnailUrl: true,
  availability: true,
  transcriptStatus: true,
  errorMessage: true,
  pageIndexDocId: true,
  summary: true,
  chunkCount: true,
  tree: true,
} as const;

type VideoRow = {
  id: string;
  videoId: string;
  title: string;
  description: string;
  channelTitle: string;
  publishedAt: Date;
  durationSeconds: number;
  thumbnailUrl: string | null;
  availability: string;
  transcriptStatus: string;
  errorMessage: string | null;
  pageIndexDocId: string | null;
  summary: string | null;
  chunkCount: number;
  tree: Prisma.JsonValue | null;
};

function toVideoRecord(row: VideoRow): VideoRecord {
  return {
    id: row.id,
    videoId: row.videoId,
    title: row.title,
    description: row.description,
    channelTitle: row.channelTitle,
    publishedAt: row.publishedAt.toISOString(),
    durationSeconds: row.durationSeconds,
    thumbnailUrl: row.thumbnailUrl,
    availability: row.availability as VideoAvailability,
    transcriptStatus: row.transcriptStatus as TranscriptStatus,
    errorMessage: row.errorMessage,
    pageIndexDocId: row.pageIndexDocId,
    summary: row.summary,
    chunkCount: row.chunkCount,
    hasTree: row.chunkCount > 0 || row.tree !== null,
  };
}

/**
 * Insert or refresh a video's metadata, leaving any existing transcript work
 * untouched — metadata is cheap to re-fetch, transcripts are not.
 */
export async function upsertVideo(
  metadata: YoutubeVideoMetadata,
): Promise<VideoRecord> {
  const shared = {
    title: metadata.title,
    description: metadata.description,
    channelTitle: metadata.channelTitle,
    publishedAt: new Date(metadata.publishedAt),
    durationSeconds: metadata.durationSeconds,
    thumbnailUrl: metadata.thumbnailUrl,
    availability: (metadata.isLive ? "live" : "available") satisfies VideoAvailability,
  };

  const row = await prisma.youtubeVideo.upsert({
    where: { videoId: metadata.videoId },
    create: { videoId: metadata.videoId, ...shared },
    update: shared,
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

export async function markVideoUnavailable(
  videoId: string,
  title: string,
): Promise<VideoRecord> {
  const shared = {
    availability: "unavailable" satisfies VideoAvailability,
    transcriptStatus: "failed",
    errorMessage: "This video is private, deleted or region blocked.",
  };

  const row = await prisma.youtubeVideo.upsert({
    where: { videoId },
    create: {
      videoId,
      title,
      description: "",
      channelTitle: "",
      publishedAt: new Date(),
      ...shared,
    },
    update: shared,
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

export async function findVideo(videoId: string): Promise<VideoRecord | null> {
  const row = await prisma.youtubeVideo.findUnique({
    where: { videoId },
    select: VIDEO_SELECT,
  });

  return row ? toVideoRecord(row) : null;
}

export async function findVideoByRowId(
  videoRowId: string,
): Promise<VideoRecord | null> {
  const row = await prisma.youtubeVideo.findUnique({
    where: { id: videoRowId },
    select: VIDEO_SELECT,
  });

  return row ? toVideoRecord(row) : null;
}

export async function updateVideoTranscript(
  videoId: string,
  data: {
    transcriptStatus: TranscriptStatus;
    errorMessage?: string | null;
    pageIndexDocId?: string | null;
    transcriptLang?: string | null;
    autoGenerated?: boolean;
    pageCount?: number | null;
    chunkCount?: number;
    summary?: string | null;
    nodes?: FlatTreeNode[];
    clearTree?: boolean;
  },
): Promise<VideoRecord> {
  const row = await prisma.youtubeVideo.update({
    where: { videoId },
    data: {
      transcriptStatus: data.transcriptStatus,
      ...(data.errorMessage === undefined
        ? {}
        : { errorMessage: data.errorMessage }),
      ...(data.pageIndexDocId === undefined
        ? {}
        : { pageIndexDocId: data.pageIndexDocId }),
      ...(data.transcriptLang === undefined
        ? {}
        : { transcriptLang: data.transcriptLang }),
      ...(data.autoGenerated === undefined
        ? {}
        : { autoGenerated: data.autoGenerated }),
      ...(data.pageCount === undefined ? {} : { pageCount: data.pageCount }),
      ...(data.chunkCount === undefined ? {} : { chunkCount: data.chunkCount }),
      ...(data.summary === undefined ? {} : { summary: data.summary }),
      ...(data.clearTree ? { tree: Prisma.DbNull } : {}),
      ...(data.nodes === undefined || data.clearTree
        ? {}
        : { tree: data.nodes as unknown as Prisma.InputJsonValue }),
    },
    select: VIDEO_SELECT,
  });

  return toVideoRecord(row);
}

/** A ready video's cached tree, for the second stage of playlist retrieval. */
export async function findVideoTrees(
  videoIds: string[],
): Promise<Map<string, FlatTreeNode[]>> {
  if (videoIds.length === 0) return new Map();

  const rows = await prisma.youtubeVideo.findMany({
    where: { videoId: { in: videoIds }, transcriptStatus: "ready" },
    select: { videoId: true, tree: true },
  });

  const trees = new Map<string, FlatTreeNode[]>();

  for (const row of rows) {
    if (Array.isArray(row.tree) && row.tree.length > 0) {
      trees.set(row.videoId, row.tree as unknown as FlatTreeNode[]);
    }
  }

  return trees;
}

/** Ready videos that still only have a legacy tree and no Qdrant chunks. */
export async function findVideosNeedingVectors(
  videoIds: string[],
): Promise<Array<{ videoId: string; title: string; nodes: FlatTreeNode[] }>> {
  if (videoIds.length === 0) return [];

  const rows = await prisma.youtubeVideo.findMany({
    where: {
      videoId: { in: videoIds },
      transcriptStatus: "ready",
      chunkCount: 0,
    },
    select: { videoId: true, title: true, tree: true },
  });

  return rows
    .map((row) => ({
      videoId: row.videoId,
      title: row.title,
      nodes: Array.isArray(row.tree) ? (row.tree as unknown as FlatTreeNode[]) : [],
    }))
    .filter((row) => row.nodes.length > 0);
}

