/**
 * Replace a playlist's membership in one transaction.
 *
 * Playlists are mutable, so a refresh has to drop videos that were removed as
 * well as add new ones; the videos themselves survive because they are cached
 * independently and may belong to other playlists.
 *
 * One upsert per video blows Prisma's 5s transaction timeout on a long
 * playlist (each statement is its own round trip). Delete-and-insert is two
 * statements no matter how many videos the playlist has. Nothing references
 * the join-row id, so replacing those rows is safe.
 */
export async function replacePlaylistItems(
  playlistRowId: string,
  items: Array<{ videoRowId: string; position: number }>,
): Promise<void> {
  // YouTube can list the same video twice. The join table keeps one row, at
  // the earliest slot.
  const positionByVideo = new Map<string, number>();
  for (const item of items) {
    const current = positionByVideo.get(item.videoRowId);
    if (current === undefined || item.position < current) {
      positionByVideo.set(item.videoRowId, item.position);
    }
  }

  const data = [...positionByVideo.entries()].map(([videoId, position]) => ({
    playlistId: playlistRowId,
    videoId,
    position,
  }));

  await prisma.$transaction(async (tx) => {
    await tx.youtubePlaylistItem.deleteMany({
      where: { playlistId: playlistRowId },
    });

    if (data.length > 0) {
      await tx.youtubePlaylistItem.createMany({ data });
    }
  });
}

/**
 * The playlist-level index: one row per video with just enough to decide which
 * video a question is about. Deliberately excludes trees and transcripts —
 * routing must stay cheap.
 */
export interface PlaylistIndexEntry {
  videoId: string;
  position: number;
  title: string;
  channelTitle: string;
  publishedAt: string;
  durationSeconds: number;
  summary: string | null;
  /** First lines of the description, as a fallback when no summary exists yet. */
  descriptionGist: string;
  availability: VideoAvailability;
  transcriptStatus: TranscriptStatus;
}

export async function loadPlaylistIndex(
  playlistId: string,
): Promise<PlaylistIndexEntry[]> {
  const rows = await prisma.youtubePlaylistItem.findMany({
    where: { playlist: { playlistId } },
    orderBy: { position: "asc" },
    select: {
      position: true,
      video: {
        select: {
          videoId: true,
          title: true,
          description: true,
          channelTitle: true,
          publishedAt: true,
          durationSeconds: true,
          summary: true,
          availability: true,
          transcriptStatus: true,
        },
      },
    },
  });

  return rows.map((row) => ({
    videoId: row.video.videoId,
    position: row.position,
    title: row.video.title,
    channelTitle: row.video.channelTitle,
    publishedAt: row.video.publishedAt.toISOString(),
    durationSeconds: row.video.durationSeconds,
    summary: row.video.summary,
    descriptionGist: row.video.description.replace(/\s+/g, " ").slice(0, 300),
    availability: row.video.availability as VideoAvailability,
    transcriptStatus: row.video.transcriptStatus as TranscriptStatus,
  }));
}

/**
 * Videos in a playlist whose transcript has not been built yet.
 *
 * A rate-limit failure is retried after the quiet period. A video left in
 * `processing` by a restart is included only once that row is a few minutes old,
 * so a download that is actually running is not started twice.
 */
export async function findUnbuiltPlaylistVideos(
  playlistId: string,
): Promise<string[]> {
  const rateLimitCooldown = new Date(Date.now() - 10 * 60 * 1000);
  const staleProcessing = new Date(Date.now() - 3 * 60 * 1000);
  const rows = await prisma.youtubePlaylistItem.findMany({
    where: {
      playlist: { playlistId },
      video: {
        availability: "available",
        OR: [
          { transcriptStatus: "pending" },
          {
            transcriptStatus: "processing",
            updatedAt: { lt: staleProcessing },
          },
          {
            transcriptStatus: "failed",
            errorMessage: { contains: "429" },
          },
          {
            transcriptStatus: "failed",
            errorMessage: { contains: "rate-limiting" },
            updatedAt: { lt: rateLimitCooldown },
          },
        ],
      },
    },
    orderBy: { position: "asc" },
    select: { video: { select: { videoId: true } } },
  });

  return rows.map((row) => row.video.videoId);
}

/** Stop a dead download from keeping the playlist on "Indexing". */
export async function releaseProcessingVideos(
  playlistId: string,
  errorMessage: string,
): Promise<void> {
  await prisma.youtubeVideo.updateMany({
    where: {
      transcriptStatus: "processing",
      playlistItems: { some: { playlist: { playlistId } } },
    },
    data: {
      transcriptStatus: "failed",
      errorMessage,
    },
  });
}

/** How far along a playlist's video transcripts are, for status reporting. */
export interface PlaylistProgress {
  totalVideos: number;
  readyVideos: number;
  pendingVideos: number;
  failedVideos: number;
}

export async function summarizePlaylistProgress(
  playlistRowId: string,
): Promise<PlaylistProgress> {
  const grouped = await prisma.youtubePlaylistItem.findMany({
    where: { playlistId: playlistRowId },
    select: { video: { select: { transcriptStatus: true } } },
  });

  const progress: PlaylistProgress = {
    totalVideos: grouped.length,
    readyVideos: 0,
    pendingVideos: 0,
    failedVideos: 0,
  };

  for (const row of grouped) {
    switch (row.video.transcriptStatus) {
      case "ready":
        progress.readyVideos += 1;
        break;
      case "failed":
        progress.failedVideos += 1;
        break;
      default:
        progress.pendingVideos += 1;
    }
  }

  return progress;
}

