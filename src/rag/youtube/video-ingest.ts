import { textToPdf } from "@/src/rag/ingest/text-to-pdf";
import { fetchTree, submitPdf } from "@/src/rag/pageindex/documents";
import { flattenTree } from "@/src/rag/pageindex/tree";
import { fetchVideo } from "@/src/rag/youtube/data-api";
import * as videos from "@/src/rag/youtube/repository";
import { summarizeVideo } from "@/src/rag/youtube/summarize";
import { fetchTranscript, TranscriptUnavailableError } from "@/src/rag/youtube/transcript";
import { renderTranscriptDocument } from "@/src/rag/youtube/transcript-document";
import type { IngestStatus } from "@/src/rag/types";

/** A failure that means "stop trying", as opposed to a transient network fault. */
export class VideoIngestError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "VideoIngestError";
  }
}

export interface VideoMetadataResult {
  videoId: string;
  title: string;
  available: boolean;
  isLive: boolean;
  reason?: string;
}

/**
 * Refresh a video's metadata. Cheap (one batched quota unit) and always safe to
 * run, so it happens for every video in a playlist even when the transcript is
 * never built.
 */
export async function syncVideoMetadata(
  videoId: string,
): Promise<VideoMetadataResult> {
  const metadata = await fetchVideo(videoId);

  if (!metadata) {
    const record = await videos.markVideoUnavailable(videoId, "Unavailable video");
    return {
      videoId,
      title: record.title,
      available: false,
      isLive: false,
      reason: "This video is private, deleted or otherwise unavailable.",
    };
  }

  const record = await videos.upsertVideo(metadata);

  return {
    videoId,
    title: record.title,
    available: !metadata.isLive,
    isLive: metadata.isLive,
    reason: metadata.isLive
      ? "This is a live or upcoming stream, so its captions are not final yet."
      : undefined,
  };
}

export interface TranscriptSubmission {
  pageIndexDocId: string;
  languageCode: string;
  autoGenerated: boolean;
  sectionCount: number;
  wordCount: number;
}

/**
 * Fetch the captions, render them as a structured document, and hand it to
 * PageIndex.
 *
 * These stages are one unit because the intermediate PDF is a binary blob that
 * cannot be passed between workflow steps; what comes out is just a document id.
 */
export async function submitVideoTranscript(
  videoId: string,
): Promise<TranscriptSubmission> {
  const record = await videos.findVideo(videoId);

  if (!record) {
    throw new VideoIngestError("The video's metadata has not been fetched yet.");
  }

  if (record.availability !== "available") {
    throw new VideoIngestError(
      record.errorMessage ?? "This video's contents cannot be read.",
    );
  }

  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "processing",
    errorMessage: null,
  });

  let transcript;
  try {
    transcript = await fetchTranscript(videoId);
  } catch (error) {
    if (error instanceof TranscriptUnavailableError) {
      throw new VideoIngestError(error.message);
    }
    throw error;
  }

  const rendered = renderTranscriptDocument(
    {
      videoId: record.videoId,
      title: record.title,
      description: record.description,
      channelTitle: record.channelTitle,
      publishedAt: record.publishedAt,
      durationSeconds: record.durationSeconds,
      thumbnailUrl: record.thumbnailUrl,
      defaultLanguage: null,
      isLive: false,
    },
    transcript,
  );

  const pdf = await textToPdf(rendered.text, { title: record.title });
  const pageIndexDocId = await submitPdf(pdf, `${videoId}.pdf`);

  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "processing",
    pageIndexDocId,
    transcriptLang: transcript.languageCode,
    autoGenerated: transcript.autoGenerated,
  });

  return {
    pageIndexDocId,
    languageCode: transcript.languageCode,
    autoGenerated: transcript.autoGenerated,
    sectionCount: rendered.sectionCount,
    wordCount: rendered.wordCount,
  };
}

export interface TreePollResult {
  status: IngestStatus;
  nodeCount: number;
}

/**
 * Advance a video's PageIndex job by one poll, caching the tree and generating
 * the routing summary the moment it is ready.
 */
export async function pollVideoTree(videoId: string): Promise<TreePollResult> {
  const record = await videos.findVideo(videoId);

  if (!record?.pageIndexDocId) {
    throw new VideoIngestError("This video has no PageIndex document to poll.");
  }

  if (record.transcriptStatus === "ready" && record.hasTree) {
    return { status: "ready", nodeCount: 0 };
  }

  const state = await fetchTree(record.pageIndexDocId);

  if (state.status === "failed") {
    await videos.updateVideoTranscript(videoId, {
      transcriptStatus: "failed",
      errorMessage: "PageIndex could not process this transcript.",
    });
    return { status: "failed", nodeCount: 0 };
  }

  if (state.status !== "ready" || !state.tree) {
    return { status: "processing", nodeCount: 0 };
  }

  const nodes = flattenTree(state.tree);

  if (nodes.length === 0) {
    await videos.updateVideoTranscript(videoId, {
      transcriptStatus: "failed",
      errorMessage: "PageIndex returned an empty transcript structure.",
    });
    return { status: "failed", nodeCount: 0 };
  }

  const pages = nodes
    .map((node) => node.pageIndex)
    .filter((page): page is number => page !== null);

  const summary = await summarizeVideo(record.title, nodes);

  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "ready",
    errorMessage: null,
    pageCount: pages.length > 0 ? Math.max(...pages) : null,
    nodes,
    summary,
  });

  return { status: "ready", nodeCount: nodes.length };
}

export async function failVideo(videoId: string, message: string): Promise<void> {
  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "failed",
    errorMessage: message,
  });
}

/** True when a video already has a usable tree, so ingest can be skipped. */
export async function isVideoIndexed(videoId: string): Promise<boolean> {
  const record = await videos.findVideo(videoId);
  return record?.transcriptStatus === "ready" && record.hasTree;
}
