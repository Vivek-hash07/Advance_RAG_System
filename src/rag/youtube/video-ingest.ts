import { fetchVideo } from "@/src/rag/youtube/data-api";
import * as videos from "@/src/rag/youtube/repository";
import { summarizeVideo } from "@/src/rag/youtube/summarize";
import { fetchTranscript, TranscriptUnavailableError } from "@/src/rag/youtube/transcript";
import { renderTranscriptDocument } from "@/src/rag/youtube/transcript-document";
import { videoUrl } from "@/src/rag/youtube/url";
import { indexVideoText } from "@/src/rag/vector/index-source";

/** A failure that means "stop trying", as opposed to a transient network fault. */
export class VideoIngestError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "VideoIngestError";
  }
}

export interface VideoMetadataResult {
  videoId: string;
  title: string;
  available: boolean;
  isLive: boolean;
  reason?: string;
}

/**
 * Refresh a video's metadata. Cheap (one batched quota unit) and always safe to
 * run, so it happens for every video in a playlist even when the transcript is
 * never built.
 */
export async function syncVideoMetadata(
  videoId: string,
): Promise<VideoMetadataResult> {
  const metadata = await fetchVideo(videoId);

  if (!metadata) {
    const record = await videos.markVideoUnavailable(videoId, "Unavailable video");
    return {
      videoId,
      title: record.title,
      available: false,
      isLive: false,
      reason: "This video is private, deleted or otherwise unavailable.",
    };
  }

  const record = await videos.upsertVideo(metadata);

  return {
    videoId,
    title: record.title,
    available: !metadata.isLive,
    isLive: metadata.isLive,
    reason: metadata.isLive
      ? "This is a live or upcoming stream, so its captions are not final yet."
      : undefined,
  };
}

export interface TranscriptIndex {
  chunkCount: number;
  languageCode: string;
  autoGenerated: boolean;
  sectionCount: number;
  wordCount: number;
}

/**
 * Fetch the captions, chunk them, and embed them in Qdrant.
 *
 * These stages stay together because the transcript is only needed long enough
 * to embed; what remains is the chunk count and a one-line routing summary.
 */
export async function indexVideoTranscript(videoId: string): Promise<TranscriptIndex> {
  const record = await videos.findVideo(videoId);

  if (!record) {
    throw new VideoIngestError("The video's metadata has not been fetched yet.");
  }

  if (record.availability !== "available") {
    throw new VideoIngestError(
      record.errorMessage ?? "This video's contents cannot be read.",
    );
  }

  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "processing",
    errorMessage: null,
  });

  let transcript;
  try {
    transcript = await fetchTranscript(videoId);
  } catch (error) {
    if (error instanceof TranscriptUnavailableError) {
      throw new VideoIngestError(error.message);
    }
    throw error;
  }

  const rendered = renderTranscriptDocument(
    {
      videoId: record.videoId,
      title: record.title,
      description: record.description,
      channelTitle: record.channelTitle,
      publishedAt: record.publishedAt,
      durationSeconds: record.durationSeconds,
      thumbnailUrl: record.thumbnailUrl,
      defaultLanguage: null,
      isLive: false,
    },
    transcript,
  );

  const indexed = await indexVideoText({
    videoId,
    title: record.title,
    sourceUrl: videoUrl(videoId),
    text: rendered.text,
  });

  const outline = rendered.text
    .split("\n")
    .filter((line) => line.startsWith("#"))
    .slice(0, 40)
    .join("\n");
  const summary = await summarizeVideo(record.title, outline || rendered.text.slice(0, 1500));

  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "ready",
    errorMessage: null,
    transcriptLang: transcript.languageCode,
    autoGenerated: transcript.autoGenerated,
    chunkCount: indexed.chunkCount,
    summary,
    clearTree: true,
  });

  return {
    chunkCount: indexed.chunkCount,
    languageCode: transcript.languageCode,
    autoGenerated: transcript.autoGenerated,
    sectionCount: rendered.sectionCount,
    wordCount: rendered.wordCount,
  };
}

export async function failVideo(videoId: string, message: string): Promise<void> {
  await videos.updateVideoTranscript(videoId, {
    transcriptStatus: "failed",
    errorMessage: message,
  });
}

/** True when a video already has vectors, or a legacy tree that can be embedded. */
export async function isVideoIndexed(videoId: string): Promise<boolean> {
  const record = await videos.findVideo(videoId);
  return Boolean(
    record &&
      record.transcriptStatus === "ready" &&
      (record.chunkCount > 0 || record.hasTree),
  );
}

const transcriptInflight = new Map<string, Promise<boolean>>();

/**
 * Embed a video's transcript unless that work is already done or in progress.
 * Returns false when the captions cannot be indexed; the video row holds why.
 */
export function ensureVideoIndexed(videoId: string): Promise<boolean> {
  const current = transcriptInflight.get(videoId);
  if (current) return current;

  const run = indexVideoIfNeeded(videoId).finally(() => {
    transcriptInflight.delete(videoId);
  });
  transcriptInflight.set(videoId, run);
  return run;
}

async function indexVideoIfNeeded(videoId: string): Promise<boolean> {
  if (await isVideoIndexed(videoId)) return true;

  try {
    await indexVideoTranscript(videoId);
    return true;
  } catch (error) {
    const message =
      error instanceof Error ? error.message : "Failed to index this video.";
    await failVideo(videoId, message);
    return false;
  }
}
